// scripts/generate-migrations-index.js
// สร้าง/อัปเดต database/MIGRATIONS_INDEX.md อัตโนมัติจาก comment หัวไฟล์ของทุก migration
// ใน database/*.sql (อ่านบรรทัด header ของแต่ละไฟล์ ไม่ต้อง maintain มือ)
//
// ทำไมต้องมีไฟล์นี้: migration file (database/NN_xxx.sql) เป็นประวัติที่ apply ไปแล้วจริงบน
// Staging/Production ห้ามรวมไฟล์/แก้ไฟล์เก่าเด็ดขาด (จะทำให้ history เพี้ยนกับ state จริงของ DB)
// แต่พอไฟล์เยอะขึ้นเรื่อยๆ (โปรเจกต์ใหญ่ๆ มี migration หลักร้อยไฟล์เป็นเรื่องปกติ - เหมือน
// Rails/Django/Prisma) ปัญหาจริงคือ "หาไม่เจอว่าไฟล์ไหนทำอะไร" ไม่ใช่ "มีไฟล์เยอะเกินไป"
// วิธีแก้ที่ถูกจุด: มีดัชนีสรุป 1 บรรทัด/ไฟล์ให้เปิดดูเร็วๆ แทนต้องเปิดอ่านทุกไฟล์
//
// ใช้งาน: node scripts/generate-migrations-index.js
// (รันทุกครั้งหลังเพิ่ม migration ใหม่ - ดู .agent-rules.md)
const fs = require('fs');
const path = require('path');

const DB_DIR = path.resolve(__dirname, '..', 'database');
const OUT_FILE = path.resolve(DB_DIR, 'MIGRATIONS_INDEX.md');

function extractTitle(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split(/\r?\n/).slice(0, 15);
  const basename = path.basename(filePath);

  const commentLines = lines
    .map(l => l.trim())
    .filter(l => l.startsWith('--'))
    .map(l => l.replace(/^--\s?/, '').trim())
    .filter(l => l.length > 0 && !/^=+$/.test(l))
    .filter(l => l !== basename && !l.endsWith(basename));

  return commentLines[0] || '(ไม่มี header comment)';
}

function main() {
  const files = fs.readdirSync(DB_DIR)
    .filter(f => /^\d+_.*\.sql$/.test(f))
    .sort();

  const rows = files.map(f => {
    const title = extractTitle(path.join(DB_DIR, f));
    return `| \`${f}\` | ${title} |`;
  });

  const out = `# database/ Migrations Index

**Auto-generated by \`scripts/generate-migrations-index.js\` — do not edit by hand.**
Run \`node scripts/generate-migrations-index.js\` after adding any new migration file to
refresh this list. This is a read-fast reference index only — the migration files
themselves are the source of truth and must never be edited/removed once applied to
Staging/Production (see \`.agent-rules.md\`).

| File | What it does |
|---|---|
${rows.join('\n')}

_Generated: ${new Date().toISOString()}_
`;

  fs.writeFileSync(OUT_FILE, out, 'utf8');
  console.log(`Wrote ${OUT_FILE} (${files.length} migration files indexed)`);
}

main();
